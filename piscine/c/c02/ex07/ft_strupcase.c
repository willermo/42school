char	*ft_strupcase(char *str)
{
	char	*idx;

	idx = str;
	while (*idx)
	{
		if (*idx >= 'a' && *idx <= 'z')
			*idx = *idx - 'a' + 'A';
		idx++;
	}
	return (str);
}
