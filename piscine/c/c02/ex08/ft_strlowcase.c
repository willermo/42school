char	*ft_strlowcase(char *str)
{
	char	*idx;

	idx = str;
	while (*idx)
	{
		if (*idx >= 'A' && *idx <= 'Z')
			*idx = *idx - 'A' + 'a';
		idx++;
	}
	return (str);
}
